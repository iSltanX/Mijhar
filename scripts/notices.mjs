#!/usr/bin/env node
// يولّد THIRD_PARTY_NOTICES.txt في جذر المستودع (AC-10.3، AD-20، MJ26): إشعارات تراخيص الأطراف الثالثة بنصوصها ونسبتها إلى أصحابها، من مصادرها الحرفية
// لا من نص يُكتب بيد: ملفات OFL في assets/fonts، وملفات الترخيص في node_modules بالإصدار المثبت من package-lock.json. قسمان: ما يُشحن داخل الحزمة
// (الخطوط وPreact)، وأدوات البناء والفحص التي لا تُشحن. ولا يُنسب شيء منها إلى المالك، ولا يضيف ترخيصًا للمشروع نفسه.
// ويُنسخ الملف إلى جذر كل حزمة (scripts/build.mjs).
// الاستعمال: node scripts/notices.mjs [--check]  (--check يفشل إن اختلف الملف المتتبَّع عمّا يولّده)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const NOTICES_FILE = 'THIRD_PARTY_NOTICES.txt';

const FONTS = [
  { name: 'Cairo', files: 'Cairo-Regular.woff2, Cairo-Bold.woff2', license: 'OFL-Cairo.txt', use: 'UI headings and Arabic reading font' },
  { name: 'Almarai', files: 'Almarai-Regular.woff2, Almarai-Bold.woff2', license: 'OFL-Almarai.txt', use: 'UI body text' },
  { name: 'IBM Plex Sans Arabic', files: 'IBMPlexSansArabic-Regular.woff2, IBMPlexSansArabic-Bold.woff2', license: 'OFL-IBMPlexSansArabic.txt', use: 'Arabic reading font' },
  { name: 'Noto Sans Arabic', files: 'NotoSansArabic-Variable.woff2', license: 'OFL-NotoSansArabic.txt', use: 'Arabic reading font' },
];
/** ما يُجمَّع في شيفرة الحزمة من node_modules (يتحقق منه tests/release/notices.test.ts مقابل الحزمة المبنية). */
export const SHIPPED_PACKAGES = ['preact'];
/** أدوات البناء والفحص من devDependencies في package.json، لا تُشحن. */
const lock = JSON.parse(fs.readFileSync(path.join(ROOT, 'package-lock.json'), 'utf8'));
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

const rule = (title) => `\n${'='.repeat(78)}\n${title}\n${'='.repeat(78)}\n`;
const read = (file) => fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trimEnd();

/** نص ترخيص الحزمة كما في ملفها، ومن LICENSE.md المجمّع (vite وvitest) قسم «core license» وحده. */
function licenseText(name) {
  const dir = path.join(ROOT, 'node_modules', name);
  const file = fs.readdirSync(dir).find((f) => /^licen[sc]e/i.test(f));
  if (!file) throw new Error(`لا ملف ترخيص لـ${name}`);
  const text = read(path.join(dir, file));
  const core = /^# .* core license\n/m.test(text) ? text.split(/\n# Licenses of bundled dependencies/)[0] : text;
  return core.replace(/^# .* core license\n.*\n\n/m, '').trim();
}
function info(name) {
  const entry = lock.packages[`node_modules/${name}`];
  if (!entry) throw new Error(`${name} غائب عن package-lock.json`);
  const meta = JSON.parse(fs.readFileSync(path.join(ROOT, 'node_modules', name, 'package.json'), 'utf8'));
  return { name, version: entry.version, license: meta.license, homepage: meta.homepage ?? meta.repository?.url ?? '' };
}

export function generate() {
  const out = [];
  out.push('THIRD-PARTY NOTICES — Mijhar (مِجهَر)');
  out.push('');
  out.push('Mijhar is designed and developed by Sultan (تصميم وتطوير سلطان) — https://bysltan.com');
  out.push('This file lists third-party works with their own copyright holders and licenses. They are not the work of the');
  out.push("Mijhar author, and nothing here changes their licenses. Mijhar's own code is not offered under any of these licenses.");
  out.push(`Generated by scripts/notices.mjs from the bundled license files (fonts) and package-lock.json (packages).`);

  out.push(rule('PART 1 — Included in the extension package'));
  out.push('1.1 Fonts (assets/fonts → fonts/ in the package). Each font is unmodified and keeps its Reserved Font Name, if any.');
  const ofl = new Map();
  for (const font of FONTS) {
    const text = read(path.join(ROOT, 'assets/fonts', font.license));
    const [head, ...rest] = text.split('\nThis Font Software is licensed under the SIL Open Font License, Version 1.1.');
    out.push('');
    out.push(`* ${font.name} — ${font.files} — used for: ${font.use}`);
    out.push(`  ${head.trim().split('\n').join('\n  ')}`);
    out.push(`  License: SIL Open Font License 1.1 (full text below; the font's own copy ships as fonts/${font.license}).`);
    ofl.set('ofl', rest.join(''));
  }
  out.push('');
  out.push('SIL Open Font License, Version 1.1 — full text:');
  out.push('');
  out.push(`This Font Software is licensed under the SIL Open Font License, Version 1.1.${ofl.get('ofl')}`.trim());

  out.push('');
  out.push('1.2 JavaScript libraries bundled into the extension code:');
  for (const name of SHIPPED_PACKAGES) {
    const i = info(name);
    out.push('');
    out.push(`* ${i.name} ${i.version} — ${i.license} — ${i.homepage}`);
    out.push('');
    out.push(licenseText(name));
  }
  out.push('');
  out.push('1.3 Models: none. Mijhar ships no machine-learning model. Local translation uses the browser\'s own built-in translator where');
  out.push('the browser provides one; optional analysis is sent only to the provider the user chooses (Anthropic, OpenAI or Google Gemini),');
  out.push("under that provider's own terms, after the user's consent for each request.");

  out.push(rule('PART 2 — Build and test tools (not included in the extension package)'));
  out.push('Used to build and verify Mijhar from source; listed for attribution. Versions are the ones locked in package-lock.json.');
  const tools = Object.keys(pkg.devDependencies ?? {}).sort();
  const texts = new Map();
  for (const name of tools) {
    const i = info(name);
    out.push(`* ${i.name} ${i.version} — ${i.license} — ${i.homepage}`);
    const text = licenseText(name);
    const key = i.license === 'MIT' ? `MIT:${name}` : i.license;
    if (!texts.has(key)) texts.set(key, { names: [name], text });
    else texts.get(key).names.push(name);
  }
  for (const [key, { names, text }] of texts) {
    out.push('');
    out.push(`--- ${key.startsWith('MIT:') ? 'MIT License' : key} — ${names.join(', ')} ---`);
    out.push('');
    out.push(text);
  }
  return `${out.join('\n')}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const file = path.join(ROOT, NOTICES_FILE);
  const text = generate();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
    if (current !== text) {
      console.error(`${NOTICES_FILE} لا يطابق ما يولّده scripts/notices.mjs؛ شغّله بلا --check`);
      process.exit(1);
    }
    console.log(`${NOTICES_FILE} مطابق`);
  } else {
    fs.writeFileSync(file, text);
    console.log(`كُتب ${NOTICES_FILE} (${Buffer.byteLength(text)} بايت)`);
  }
}
